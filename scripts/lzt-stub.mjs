/** Init script injected before the app's own scripts run. */
export function lztInitScript() {
  const payload = JSON.stringify({ STATE, CONFIG, CHANGELOG });
  return [
    "(() => {",
    "  const D = " + payload + ";",
    "  const ok = (v) => Promise.resolve(v);",
    "  const base = {",
    "    get_state: (version) => ok(version === D.STATE.version",
    "      ? { version: D.STATE.version, same: true }",
    "      : D.STATE),",
    "    get_config: () => ok(D.CONFIG),",
    "    changelog: () => ok(D.CHANGELOG),",
    "    changelog_seen: () => ok(true),",
    "    version: () => ok(D.CHANGELOG.version),",
    "    lzt_login_available: () => ok(true),",
    "    test_filter: () => ok({ ok: true, count: 12 }),",
    "    tg_preview: () => ok({ ok: true, text: '' }),",
    "  };",
    "  window.pywebview = {",
    "    api: new Proxy(base, {",
    "      get: (t, k) => (k in t ? t[k] : () => ok({ ok: true })),",
    "    }),",
    "  };",
    "  // headless Chromium has no audio device; the app beeps on new finds",
    "  window.AudioContext = undefined;",
    "  window.webkitAudioContext = undefined;",
    "})();",
  ].join("\n");
}
